# --- 9a. Define Shared State ---
class CreditRiskState(TypedDict):
    borrower_input: dict                # Raw borrower data
    ml_prediction: str                  # Output from ML model tool
    risk_metrics: str                   # Output from risk calculator
    policy_context: str                 # Output from RAG retrieval
    red_flags: list                     # Identified red flags
    risk_level: str                     # LOW / MODERATE / HIGH / CRITICAL
    final_report: str                   # Generated final report
    chat_history: List[str]             # Conversation history


# --- 9b. Agent 1: Data Analyst Node ---
def data_analyst_agent(state: CreditRiskState) -> CreditRiskState:
    """
    Agent 1: Runs ML prediction and calculates risk metrics.
    Uses predict_credit_risk and calculate_risk_metrics tools.
    """
    print("🔢 Agent 1 (Data Analyst): Running ML prediction & risk calculations...")

    borrower = state["borrower_input"]

    # Run ML prediction tool
    ml_input = json.dumps(borrower)
    ml_result = predict_credit_risk.invoke(ml_input)

    # Run risk calculator tool
    calc_input = json.dumps({
        "person_age": borrower["person_age"],
        "person_income": borrower["person_income"],
        "person_emp_length": borrower["person_emp_length"],
        "loan_amnt": borrower["loan_amnt"],
        "loan_int_rate": borrower["loan_int_rate"]
    })
    risk_result = calculate_risk_metrics.invoke(calc_input)

    # Parse risk level from ML result
    try:
        ml_data = json.loads(ml_result)
        risk_level = ml_data.get("risk_level", "UNKNOWN")
    except:
        risk_level = "UNKNOWN"

    # Parse red flags from risk calculation
    try:
        risk_data = json.loads(risk_result)
        red_flags = risk_data.get("red_flags", [])
    except:
        red_flags = []

    state["ml_prediction"] = ml_result
    state["risk_metrics"] = risk_result
    state["risk_level"] = risk_level
    state["red_flags"] = red_flags

    print(f"   ✅ Risk Level: {risk_level} | Red Flags: {len(red_flags)}")
    return state


# --- 9c. Agent 2: Policy & Compliance Agent (RAG) ---
def policy_compliance_agent(state: CreditRiskState) -> CreditRiskState:
    """
    Agent 2: Retrieves relevant policies using RAG and checks compliance.
    Uses lookup_credit_policy tool and LLM for reasoning.
    """
    print("📚 Agent 2 (Policy & Compliance): Retrieving policies & checking compliance...")

    borrower = state["borrower_input"]
    risk_level = state["risk_level"]

    # Build targeted queries based on borrower profile
    queries = [
        f"What are the criteria for loan grade {borrower.get('loan_grade', 'C')} loans?",
        f"What are the rules for {borrower.get('loan_intent', 'PERSONAL')} purpose loans?",
        f"What are automatic rejection criteria for credit risk?",
    ]

    # Add risk-specific queries
    if risk_level in ["HIGH", "CRITICAL"]:
        queries.append("What are risk mitigation recommendations for high risk borrowers?")

    if borrower.get("cb_person_default_on_file") == "Y":
        queries.append("What are the rules for borrowers with previous defaults?")

    # Retrieve policies for all queries
    all_policies = ""
    for query in queries:
        result = lookup_credit_policy.invoke(query)
        all_policies += result + "\n"

    # Use LLM to analyze compliance
    compliance_prompt = f"""You are a Credit Risk Compliance Officer. Based on the retrieved policies and borrower profile, provide a compliance analysis.

BORROWER PROFILE:
{json.dumps(borrower, indent=2)}

RISK LEVEL FROM ML MODEL: {risk_level}

RED FLAGS IDENTIFIED: {json.dumps(state.get('red_flags', []))}

RETRIEVED POLICIES:
{all_policies}

Provide a structured compliance analysis:
1. POLICY VIOLATIONS (list any policies the borrower violates)
2. COMPLIANCE STATUS (COMPLIANT / PARTIALLY COMPLIANT / NON-COMPLIANT)
3. APPLICABLE REGULATIONS (which regulations apply)
4. REQUIRED ACTIONS (what actions are needed before approval)

Be specific and cite the policy documents."""

    compliance_response = llm.invoke(compliance_prompt)

    state["policy_context"] = compliance_response.content
    print(f"   ✅ Policy analysis complete")
    return state


