# --- Tool 1: ML Risk Prediction ---
@tool
def predict_credit_risk(input_json: str) -> str:
    """
    Predicts credit risk using the Random Forest ML model.
    Input must be a JSON string containing the borrower's features.
    """
    try:
        data = json.loads(input_json)

        # 1. Convert dict to DataFrame
        input_df = pd.DataFrame([data])

        # 2. Match the columns to X (the features used during training)
        # Reindexing ensures the columns are in the exact same order as the training set
        input_df = input_df.reindex(columns=X.columns, fill_value=0)

        # 3. Predict using the 'model' variable from your earlier cell
        prediction = model.predict(input_df)[0]
        probability = model.predict_proba(input_df)[0]

        result = {
            "prediction": "DEFAULT (HIGH RISK)" if prediction == 1 else "NO DEFAULT (LOW RISK)",
            "default_probability": f"{probability[1]:.4f}",
            "no_default_probability": f"{probability[0]:.4f}",
            "risk_level": (
                "CRITICAL" if probability[1] > 0.6 else
                "HIGH" if probability[1] > 0.3 else
                "MODERATE" if probability[1] > 0.1 else
                "LOW"
            ),
            "model_info": "Random Forest Classifier (93.62% accuracy)"
        }

        return json.dumps(result, indent=2)

    except Exception as e:
        return f"Error in prediction: {str(e)}"


# --- Tool 2: Policy Lookup (RAG Retrieval) ---
@tool
def lookup_credit_policy(query: str) -> str:
    """
    Searches the credit risk knowledge base for relevant policies.
    """
    try:
        # Using 'vector_store' from your Cell 7
        docs = vector_store.similarity_search(query, k=3)

        formatted = "📚 RETRIEVED POLICY DOCUMENTS:\n\n"
        for i, doc in enumerate(docs, 1):
            formatted += f"--- Source {i}: {doc.metadata['source']} ---\n"
            formatted += f"{doc.page_content}\n\n"

        return formatted

    except Exception as e:
        return f"Error in policy lookup: {str(e)}"


# --- Tool 3: Risk Calculator (Financial Logic) ---
@tool
def calculate_risk_metrics(input_json: str) -> str:
    """
    Calculates financial risk metrics (DTI, Payment-to-Income).
    Input JSON needs: person_income, loan_amnt, loan_int_rate, person_age, person_emp_length
    """
    try:
        data = json.loads(input_json)
        income = data['person_income']
        loan_amt = data['loan_amnt']
        rate = data['loan_int_rate']
        age = data['person_age']
        emp_len = data['person_emp_length']

        dti = loan_amt / income if income > 0 else 999
        # Approximate monthly payment over 3 years
        monthly_payment = (loan_amt * (1 + (rate/100))) / 36

        red_flags = []
        if dti > 0.5: red_flags.append(f"High DTI: {dti:.2f}")
        if age < 23 and loan_amt > 30000: red_flags.append("Young borrower with high loan")

        result = {
            "debt_to_income_ratio": f"{dti:.4f}",
            "estimated_monthly_payment": f"${monthly_payment:,.2f}",
            "red_flags": red_flags if red_flags else ["None"]
        }
        return json.dumps(result, indent=2)
    except Exception as e:
        return f"Error in calculation: {str(e)}"

